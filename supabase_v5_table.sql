-- ==============================================================================
-- Supabase SQL Schema Script for Quiz v5 (Remodel Readiness Diagnostic)
-- Table: quiz_submissions_v5
-- Identical in structure to the existing quiz_submissions table
-- ==============================================================================

-- 1. Create table quiz_submissions_v5
CREATE TABLE IF NOT EXISTS quiz_submissions_v5 (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  first_name TEXT,
  last_name TEXT,
  email TEXT,
  phone TEXT,
  business_name TEXT,
  website_url TEXT,
  quiz_tag TEXT,
  score INTEGER,
  answers JSONB,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Add column comments for clarity
COMMENT ON TABLE quiz_submissions_v5 IS 'Lead submissions and quiz results specifically for Quiz v5 (Remodel Readiness Diagnostic)';
COMMENT ON COLUMN quiz_submissions_v5.first_name IS 'First name of the respondent';
COMMENT ON COLUMN quiz_submissions_v5.last_name IS 'Last name of the respondent';
COMMENT ON COLUMN quiz_submissions_v5.email IS 'Email address of the respondent';
COMMENT ON COLUMN quiz_submissions_v5.phone IS 'Phone number of the respondent (if provided)';
COMMENT ON COLUMN quiz_submissions_v5.business_name IS 'Business Name (if provided)';
COMMENT ON COLUMN quiz_submissions_v5.website_url IS 'Website URL (if provided)';
COMMENT ON COLUMN quiz_submissions_v5.quiz_tag IS 'Result tier / tag (e.g. Well-Prepared, Moderately Prepared, Unprepared)';
COMMENT ON COLUMN quiz_submissions_v5.score IS 'Total calculated score';
COMMENT ON COLUMN quiz_submissions_v5.answers IS 'Full JSON payload containing category breakdown, answers, and recommendation details';
COMMENT ON COLUMN quiz_submissions_v5.created_at IS 'Timestamp of when the submission occurred';

-- 3. Enable Row Level Security (RLS)
ALTER TABLE quiz_submissions_v5 ENABLE ROW LEVEL SECURITY;

-- 4. Policies to allow public/anonymous inserts from quiz submissions
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies 
    WHERE tablename = 'quiz_submissions_v5' 
    AND policyname = 'Allow anonymous insert to quiz_submissions_v5'
  ) THEN
    CREATE POLICY "Allow anonymous insert to quiz_submissions_v5"
      ON quiz_submissions_v5
      FOR INSERT
      TO anon, authenticated
      WITH CHECK (true);
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_policies 
    WHERE tablename = 'quiz_submissions_v5' 
    AND policyname = 'Allow read access to quiz_submissions_v5'
  ) THEN
    CREATE POLICY "Allow read access to quiz_submissions_v5"
      ON quiz_submissions_v5
      FOR SELECT
      TO anon, authenticated
      USING (true);
  END IF;
END $$;
